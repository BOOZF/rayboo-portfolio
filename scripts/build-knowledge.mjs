// Builds knowledge/index.js from knowledge/*.md: one entry per "## " section, embedded with OpenAI.
// Run after editing the knowledge files: npm run knowledge
import fs from 'node:fs';
import path from 'node:path';
import { embedMany, EMBED_DIMS } from '../server/openai.js';

const dir = path.resolve(import.meta.dirname, '../knowledge');
if (fs.existsSync('.env')) process.loadEnvFile('.env');
const key = process.env.OPENAI_API_KEY;
if (!key) throw new Error('OPENAI_API_KEY missing (.env or environment)');

const sections = fs.readdirSync(dir).filter(f => f.endsWith('.md')).sort().flatMap(file => {
  const md = fs.readFileSync(path.join(dir, file), 'utf8'), title = (md.match(/^# (.+)$/m) || [, file])[1];
  return md.split(/^## /m).slice(1).map(part => {
    const [heading, ...body] = part.split('\n');
    return { id:file.replace(/\.md$/, '') + '#' + heading.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-'), text:`${title} — ${heading.trim()}\n${body.join('\n').trim()}` };
  });
});
// the site's FAQ (src/content/faq.js) doubles as knowledge: each question is phrased the way visitors ask
// (the Chinese FAQ too, so questions asked in Chinese find a section written in Chinese)
const { FAQ } = await import('../src/content/faq.js'), { FAQ:FAQ_ZH } = await import('../src/content/faq.zh.js');
sections.push(...FAQ.map(({ q, a }) => ({ id:'faq#' + q.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''), text:`FAQ — ${q}\n${a}` })));
sections.push(...FAQ_ZH.map(({ q, a }, i) => ({ id:'faq-zh#' + (i + 1), text:`常见问题 — ${q}\n${a}` })));
const vectors = await embedMany(sections.map(s => s.text), key);
const index = sections.map((s, i) => ({ ...s, vector:vectors[i].map(v => +v.toFixed(5)) }));
fs.writeFileSync(path.join(dir, 'index.js'), `// Generated by scripts/build-knowledge.mjs from knowledge/*.md (${EMBED_DIMS}-d embeddings). Do not edit by hand.\nexport default ${JSON.stringify(index)};\n`);
console.log(`knowledge/index.js: ${index.length} sections`);
